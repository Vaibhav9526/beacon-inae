export function templateById(id: string): Template | undefined {
  return TEMPLATES.find((t) => t.id === id);
}

export function instantiate(t: Template, over: Partial<Agent> = {}): Agent {
  const base = structuredClone(t.agent);
  return {
    ...base,
    ...over,
    id: randomUUID(),
    templateId: t.id,
    createdAt: Date.now(),
  } as Agent;
}
